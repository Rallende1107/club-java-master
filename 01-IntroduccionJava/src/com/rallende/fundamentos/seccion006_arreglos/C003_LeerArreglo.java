package com.rallende.fundamentos.seccion006_arreglos;

public class C003_LeerArreglo {
    public static void main(String[] args) {
        // declarar arreglo
        int [] enteros;
        // Inicializar
        enteros = new  int[5];

        enteros [0] = 10;
        enteros [1] = 11;
        enteros [2] = 13;
        System.out.println("Valor 1: " + enteros[0]);
        System.out.println("Valor 2: " + enteros[1]);
        System.out.println("Valor 3: " + enteros[2]);
    }
}
