package com.rallende.fundamentos.seccion002_variables;
public class C001_Variables {
    public static void main(String[] args) {
        // Variables
        int numero = 30;
        double decimal = 320.5;
        String nombre = "Rene Enrique Allende Allende";

        System.out.println("numero: " + numero);
        System.out.println("decimal: " + decimal);
        System.out.println("nombre: " + nombre);
        // modificando Valores de variables
        numero = 80;
        decimal = 35.5;
        nombre = "Maria del pilar Allende Catalan";
        System.out.println("numero: " + numero);
        System.out.println("decimal: " + decimal);
        System.out.println("nombre: " + nombre);
    }
}
